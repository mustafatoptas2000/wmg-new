// High-detail port plan blueprint features generated deterministically per marina
export interface PortPlanFeature {
  id: string;
  label: string;
  kind: 'fairway' | 'fuel' | 'customs' | 'anchorage' | 'travel_lift' | 'berth';
  relX: number; // -100..100 relative harbor plan coordinate
  relY: number;
  depthM: number;
  vhf?: string;
}

